struct PostBuild<'a> {
    device: &'a Device,
    pipeline: Option<vk::Pipeline>,
    fast_pipeline: Option<vk::Pipeline>,
    pipeline_layout: Option<vk::PipelineLayout>,
    pass_set_layout: Option<vk::DescriptorSetLayout>,
    empty_set_layout: Option<vk::DescriptorSetLayout>,
    descriptor_pool: Option<vk::DescriptorPool>,
    descriptor_sets: Vec<vk::DescriptorSet>,
    color_sampler: Option<vk::Sampler>,
    data_sampler: Option<vk::Sampler>,
    finished: bool,
}

impl<'a> PostBuild<'a> {
    /// Starts a guarded post-pipeline build that cleans up unless `finish` consumes it.
    fn new(device: &'a Device) -> Self {
        Self {
            device,
            pipeline: None,
            fast_pipeline: None,
            pipeline_layout: None,
            pass_set_layout: None,
            empty_set_layout: None,
            descriptor_pool: None,
            descriptor_sets: Vec::new(),
            color_sampler: None,
            data_sampler: None,
            finished: false,
        }
    }

    /// Moves all successfully-created objects into the runtime pipeline owner.
    fn finish(mut self) -> PostPipeline {
        let pipeline = take_created(&mut self.pipeline, "post pipeline");
        let fast_pipeline = take_created(&mut self.fast_pipeline, "fast post pipeline");
        let pipeline_layout = take_created(&mut self.pipeline_layout, "post pipeline layout");
        let pass_set_layout = take_created(&mut self.pass_set_layout, "post pass set layout");
        let empty_set_layout = take_created(&mut self.empty_set_layout, "post empty set layout");
        let descriptor_pool = take_created(&mut self.descriptor_pool, "post descriptor pool");
        let descriptor_sets = std::mem::take(&mut self.descriptor_sets);
        let color_sampler = take_created(&mut self.color_sampler, "post color sampler");
        let data_sampler = take_created(&mut self.data_sampler, "post data sampler");
        self.finished = true;

        PostPipeline {
            pipeline,
            fast_pipeline,
            pipeline_layout,
            pass_set_layout,
            empty_set_layout,
            descriptor_pool,
            descriptor_sets,
            color_sampler,
            data_sampler,
        }
    }

    /// Returns the empty set layout after it has been created.
    fn empty_set_layout(&self) -> vk::DescriptorSetLayout {
        expect_created(self.empty_set_layout, "post empty set layout")
    }

    /// Returns the pass set layout after it has been created.
    fn pass_set_layout(&self) -> vk::DescriptorSetLayout {
        expect_created(self.pass_set_layout, "post pass set layout")
    }

    /// Returns the pipeline layout after it has been created.
    fn pipeline_layout(&self) -> vk::PipelineLayout {
        expect_created(self.pipeline_layout, "post pipeline layout")
    }

    /// Returns the descriptor pool after it has been created.
    fn descriptor_pool(&self) -> vk::DescriptorPool {
        expect_created(self.descriptor_pool, "post descriptor pool")
    }

    /// Returns the descriptor set after it has been allocated.
    /// Returns the color sampler after it has been created.
    fn color_sampler(&self) -> vk::Sampler {
        expect_created(self.color_sampler, "post color sampler")
    }

    /// Returns the metadata sampler after it has been created.
    fn data_sampler(&self) -> vk::Sampler {
        expect_created(self.data_sampler, "post data sampler")
    }
}

impl Drop for PostBuild<'_> {
    /// Releases partially-created post resources when creation fails.
    fn drop(&mut self) {
        if self.finished {
            return;
        }

        if let Some(pipeline) = self.pipeline.take() {
            destroy_pipeline(self.device, pipeline);
        }
        if let Some(pipeline) = self.fast_pipeline.take() {
            destroy_pipeline(self.device, pipeline);
        }
        if let Some(pool) = self.descriptor_pool.take() {
            destroy_descriptor_pool(self.device, pool);
        }
        if let Some(sampler) = self.data_sampler.take() {
            destroy_sampler(self.device, sampler);
        }
        if let Some(sampler) = self.color_sampler.take() {
            destroy_sampler(self.device, sampler);
        }
        if let Some(layout) = self.pipeline_layout.take() {
            destroy_pipeline_layout(self.device, layout);
        }
        if let Some(layout) = self.pass_set_layout.take() {
            destroy_descriptor_set_layout(self.device, layout);
        }
        if let Some(layout) = self.empty_set_layout.take() {
            destroy_descriptor_set_layout(self.device, layout);
        }
    }
}

#[repr(C)]
#[derive(Clone, Copy, Default)]
struct PostPushConstants {
    white_balance: [f32; 4],
    camera: [f32; 4],
    depth: [f32; 4],
    ssao: [f32; 4],
    ssr: [f32; 4],
    aa: [f32; 4],
    bloom: [f32; 4],
    features: [f32; 4],
    god_ray_source0: [f32; 4],
    god_ray_color0: [f32; 4],
    god_ray_source1: [f32; 4],
    god_ray_color1: [f32; 4],
    temporal: [f32; 4],
    exposure: f32,
    contrast: f32,
    saturation: f32,
    enabled: f32,
}

pub(super) const POST_PUSH_CONSTANT_SIZE: u32 = size_of::<PostPushConstants>() as u32;

impl PostPushConstants {
    /// Packs camera, look, and renderer quality state into the fragment push-constant layout.
    fn new(
        camera_effects: CameraEffects,
        camera: CameraSnapshot,
        extent: vk::Extent2D,
        quality: RenderQualitySettings,
        has_transparent_scene_items: bool,
        god_ray_history_index: usize,
        directional_light: LightPacket,
        emissive_lights: EmissiveLightUniforms,
        debug_view_mode: DebugViewMode,
        jitter_pixels: [f32; 2],
        taa_stable_metadata_valid: bool,
    ) -> Self {
        let white_balance = camera_effects.white_balance();
        let ssao = quality.ssao();
        let ssr = quality.ssr();
        let anti_aliasing = quality.anti_aliasing();
        let bloom = quality.bloom();
        // Match the frame graph's explicit feature route. Continuous bloom/god-ray values remain
        // available to the selected path but do not choose that path by themselves.
        let volumetric = quality.features().volumetric_fog_enabled();
        let post = quality.post();
        let camera_params = Self::camera_params(camera, extent);
        let god_ray_sources =
            frame_god_ray_sources(camera, extent, quality, directional_light, emissive_lights);

        Self {
            // Alpha is unused by color grading; carry jitter NDC X so post can map its stable
            // output grid back to the current jittered scene metadata.
            white_balance: [
                white_balance[0],
                white_balance[1],
                white_balance[2],
                jitter_pixels[0] * 2.0 / extent.width.max(1) as f32,
            ],
            camera: camera_params,
            depth: Self::depth_params(camera),
            ssao: [
                ssao.intensity(),
                ssao.radius(),
                ssao.bias(),
                ssao.sample_count() as f32,
            ],
            ssr: [
                ssr.intensity(),
                ssr.max_steps() as f32,
                ssr.max_distance(),
                ssr.thickness(),
            ],
            aa: Self::aa_params(extent, anti_aliasing),
            bloom: Self::bloom_params(bloom),
            features: [
                if has_transparent_scene_items {
                    1.0
                } else {
                    0.0
                },
                god_ray_history_index.min(1) as f32,
                debug_view_mode as u32 as f32,
                jitter_pixels[1] * 2.0 / extent.height.max(1) as f32,
            ],
            god_ray_source0: if volumetric {
                [0.0; 4]
            } else {
                god_ray_sources[0].source
            },
            god_ray_color0: if volumetric {
                [0.0; 4]
            } else {
                god_ray_sources[0].color
            },
            god_ray_source1: if volumetric {
                [0.0; 4]
            } else {
                god_ray_sources[1].source
            },
            god_ray_color1: if volumetric {
                // Alpha > 1 marks the dedicated volumetric composite to post_god_rays.
                [0.0, 0.0, 0.0, 2.0]
            } else {
                god_ray_sources[1].color
            },
            // The renderer's production SMAA graph leaves temporal metadata disabled. A legacy
            // temporal caller can still opt into the stable attachments; otherwise post reads the
            // current raw scene depth/normal through `post_metadata_uv`.
            temporal: [
                if taa_stable_metadata_valid { 1.0 } else { 0.0 },
                quality.features().bits() as f32,
                0.0,
                0.0,
            ],
            exposure: camera_effects.exposure().value(),
            contrast: (camera_effects.contrast() * post.contrast()).clamp(0.25, 4.0),
            saturation: (camera_effects.saturation() * post.saturation()).clamp(0.0, 4.0),
            enabled: if camera_effects.enabled() { 1.0 } else { 0.0 },
        }
    }

    /// Packs perspective coefficients reused by view reconstruction and SSR reprojection.
    fn camera_params(camera: CameraSnapshot, extent: vk::Extent2D) -> [f32; 4] {
        let aspect = (extent.width as f32 / extent.height.max(1) as f32).max(0.0001);
        let tan_half_fov = (camera.fov_y_radians * 0.5).tan();
        let tan_half_fov = if tan_half_fov.is_finite() && tan_half_fov > 0.0001 {
            tan_half_fov
        } else {
            0.57735026
        };
        let f = 1.0 / tan_half_fov;
        let focal_x = f / aspect;
        let focal_y = -f;

        [focal_x, focal_y, 1.0 / focal_x, 1.0 / focal_y]
    }

    /// Packs reusable perspective depth constants for post-pass reconstruction.
    fn depth_params(camera: CameraSnapshot) -> [f32; 4] {
        let near = camera.near.max(0.0001);
        let far = camera.far.max(near + 0.001);
        [near, far, near * far, far - near]
    }

    /// Packs texel size and SMAA edge controls used by the post fragment shader.
    fn aa_params(extent: vk::Extent2D, anti_aliasing: AntiAliasingQualitySettings) -> [f32; 4] {
        [
            1.0 / extent.width.max(1) as f32,
            1.0 / extent.height.max(1) as f32,
            anti_aliasing.edge_threshold(),
            anti_aliasing.blend(),
        ]
    }

    /// Packs the single-pass bloom controls.
    fn bloom_params(bloom: BloomQualitySettings) -> [f32; 4] {
        [
            bloom.intensity(),
            bloom.threshold(),
            bloom.radius_pixels(),
            bloom.god_rays_intensity(),
        ]
    }

    /// Uses the one-sample composition shader when every composition effect is disabled by its
    /// packed runtime values. The three-pass SMAA chain is separate and therefore does not affect
    /// this selection. These comparisons intentionally match the Slang enable predicates.
    fn uses_fast_pipeline(self) -> bool {
        let features = RenderFeatureToggles::from_bits(self.temporal[1] as u32);
        let ssao_enabled = features.ssao_enabled() && self.ssao[0] > 0.0;
        let ssr_enabled = features.ssr_enabled() && self.ssr[0] > 0.0 && self.ssr[1] >= 1.0;
        let bloom_enabled = features.bloom_enabled() && self.bloom[0] > 0.0;
        let debug_view_enabled = self.features[2] > 0.0;
        let god_rays_enabled = features.god_rays_enabled()
            && (self.god_ray_color1[3] > 1.5
                || (self.bloom[3] > 0.0
                    && (self.god_ray_source0[3] > 0.0 || self.god_ray_source1[3] > 0.0)));

        !(ssao_enabled || ssr_enabled || bloom_enabled || god_rays_enabled || debug_view_enabled)
    }
}

impl PostPipeline {
    /// Creates the post-composition pipeline that samples scene color and writes `PostColor`.
    pub(super) fn create(
        device: &Device,
        render_pass: vk::RenderPass,
        scene_color_view: vk::ImageView,
        scene_depth_view: vk::ImageView,
        scene_normal_roughness_view: vk::ImageView,
        scene_transparent_normal_roughness_view: vk::ImageView,
        bloom_view: vk::ImageView,
        god_ray_history_views: [vk::ImageView; 2],
    ) -> Result<Self, VulkanError> {
        let mut build = PostBuild::new(device);
        build.empty_set_layout = Some(create_empty_set_layout(device)?);
        build.pass_set_layout = Some(create_pass_set_layout(device)?);
        build.pipeline_layout = Some(create_pipeline_layout(
            device,
            build.empty_set_layout(),
            build.pass_set_layout(),
        )?);
        build.color_sampler = Some(create_sampler(device, vk::Filter::LINEAR)?);
        build.data_sampler = Some(create_sampler(device, vk::Filter::NEAREST)?);
        build.descriptor_pool = Some(create_descriptor_pool(device)?);
        build.descriptor_sets =
            allocate_descriptor_sets(device, build.descriptor_pool(), build.pass_set_layout(), 1)?;
        update_descriptor_set(
            device,
            build.descriptor_sets[0],
            scene_color_view,
            scene_depth_view,
            scene_normal_roughness_view,
            scene_transparent_normal_roughness_view,
            bloom_view,
            god_ray_history_views,
            build.color_sampler(),
            build.data_sampler(),
        );
        build.pipeline = Some(create_post_pipeline(
            device,
            build.pipeline_layout(),
            render_pass,
            FRAGMENT_SHADER,
        )?);
        build.fast_pipeline = Some(create_post_pipeline(
            device,
            build.pipeline_layout(),
            render_pass,
            FAST_FRAGMENT_SHADER,
        )?);

        tracing::info!("created Vulkan full and fast post-composition pipelines");
        Ok(build.finish())
    }

    /// Records the full-screen post pass that resolves the scene color into the
    /// intermediate post-color target. The following dedicated SMAA chain consumes that complete
    /// result, so this pass never has to reconstruct neighbor colors itself.
    pub(super) fn draw(
        &self,
        device: &Device,
        command_buffer: vk::CommandBuffer,
        extent: vk::Extent2D,
        camera_effects: CameraEffects,
        camera: CameraSnapshot,
        quality: RenderQualitySettings,
        has_transparent_scene_items: bool,
        god_ray_history_index: usize,
        directional_light: LightPacket,
        emissive_lights: EmissiveLightUniforms,
        debug_view_mode: DebugViewMode,
        jitter_pixels: [f32; 2],
        taa_stable_metadata_valid: bool,
    ) {
        let viewports = [vk::Viewport::default()
            .x(0.0)
            .y(0.0)
            .width(extent.width as f32)
            .height(extent.height as f32)
            .min_depth(0.0)
            .max_depth(1.0)];
        let scissors = [vk::Rect2D::default()
            .offset(vk::Offset2D { x: 0, y: 0 })
            .extent(extent)];
        let descriptor_set = self.descriptor_sets[0];
        let descriptor_sets = [descriptor_set];
        let push = PostPushConstants::new(
            camera_effects,
            camera,
            extent,
            quality,
            has_transparent_scene_items,
            god_ray_history_index,
            directional_light,
            emissive_lights,
            debug_view_mode,
            jitter_pixels,
            taa_stable_metadata_valid,
        );
        let fast_path = push.uses_fast_pipeline();
        let pipeline = if fast_path {
            self.fast_pipeline
        } else {
            self.pipeline
        };
        let push_bytes = push_constant_bytes(&push);

        tracing::trace!(
            width = extent.width,
            height = extent.height,
            exposure = push.exposure,
            white_balance = ?push.white_balance,
            contrast = push.contrast,
            saturation = push.saturation,
            enabled = camera_effects.enabled(),
            ssao_intensity = push.ssao[0],
            ssao_slices = quality.ssao().slice_count(),
            ssao_steps_per_slice = quality.ssao().steps_per_slice(),
            ssao_depth_taps = quality.ssao().sample_budget(),
            ssr_intensity = push.ssr[0],
            ssr_steps = push.ssr[1],
            aa_threshold = push.aa[2],
            aa_blend = push.aa[3],
            bloom_intensity = push.bloom[0],
            bloom_threshold = push.bloom[1],
            bloom_radius = push.bloom[2],
            god_rays_intensity = push.bloom[3],
            feature_bits = push.temporal[1] as u32,
            debug_view = push.features[2],
            god_ray_source0 = ?push.god_ray_source0,
            god_ray_source1 = ?push.god_ray_source1,
            has_transparent_scene_items,
            fast_path,
            "recording Vulkan post pass"
        );

        // Safety: the command buffer is inside the post render pass, the pipeline is compatible
        // with that pass, and the descriptor set points at the live scene color image view.
        unsafe {
            device.cmd_bind_pipeline(command_buffer, vk::PipelineBindPoint::GRAPHICS, pipeline);
            device.cmd_set_viewport(command_buffer, 0, &viewports);
            device.cmd_set_scissor(command_buffer, 0, &scissors);
            device.cmd_bind_descriptor_sets(
                command_buffer,
                vk::PipelineBindPoint::GRAPHICS,
                self.pipeline_layout,
                shader_interface::PASS_SET,
                &descriptor_sets,
                &[],
            );
            device.cmd_push_constants(
                command_buffer,
                self.pipeline_layout,
                vk::ShaderStageFlags::FRAGMENT,
                0,
                push_bytes,
            );
            device.cmd_draw(command_buffer, 3, 1, 0, 0);
        }
    }

    /// Destroys all swapchain-dependent post resources.
    pub(super) fn destroy(self, device: &Device) {
        destroy_pipeline(device, self.fast_pipeline);
        destroy_pipeline(device, self.pipeline);
        destroy_descriptor_pool(device, self.descriptor_pool);
        destroy_sampler(device, self.data_sampler);
        destroy_sampler(device, self.color_sampler);
        destroy_pipeline_layout(device, self.pipeline_layout);
        destroy_descriptor_set_layout(device, self.pass_set_layout);
        destroy_descriptor_set_layout(device, self.empty_set_layout);
    }
}

#[repr(C)]
#[derive(Clone, Copy, Default)]
struct SmaaPushConstants {
    aa: [f32; 4],
    depth: [f32; 4],
    debug: [f32; 4],
}

impl SmaaPushConstants {
    fn new(
        extent: vk::Extent2D,
        anti_aliasing: AntiAliasingQualitySettings,
        anti_aliasing_enabled: bool,
        camera: CameraSnapshot,
        debug_view_mode: DebugViewMode,
    ) -> Self {
        let near = camera.near.max(0.0001);
        let far = camera.far.max(near + 0.001);
        Self {
            aa: [
                1.0 / extent.width.max(1) as f32,
                1.0 / extent.height.max(1) as f32,
                anti_aliasing.edge_threshold(),
                if debug_view_mode == DebugViewMode::Disabled {
                    anti_aliasing.blend()
                } else {
                    0.0
                },
            ],
            depth: [near, far, near * far, far - near],
            debug: [
                debug_view_mode as u32 as f32,
                if anti_aliasing_enabled { 1.0 } else { 0.0 },
                0.0,
                0.0,
            ],
        }
    }
}

/// Owns the canonical three-pass SMAA 1x chain.
