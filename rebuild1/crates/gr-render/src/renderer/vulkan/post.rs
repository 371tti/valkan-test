/// Writes sampled scene color, depth, and normal/roughness images into the post descriptor set.
fn update_descriptor_set(
    device: &Device,
    descriptor_set: vk::DescriptorSet,
    scene_color_view: vk::ImageView,
    scene_depth_view: vk::ImageView,
    scene_normal_roughness_view: vk::ImageView,
    scene_transparent_normal_roughness_view: vk::ImageView,
    bloom_view: vk::ImageView,
    god_ray_history_views: [vk::ImageView; 2],
    color_sampler: vk::Sampler,
    data_sampler: vk::Sampler,
) {
    let color_info = [post_image_info(color_sampler, scene_color_view)];
    let depth_info = [post_image_info(data_sampler, scene_depth_view)];
    let normal_roughness_info = [post_image_info(data_sampler, scene_normal_roughness_view)];
    let transparent_normal_roughness_info = [post_image_info(
        data_sampler,
        scene_transparent_normal_roughness_view,
    )];
    let bloom_info = [post_image_info(color_sampler, bloom_view)];
    let god_ray_0_info = [post_image_info(color_sampler, god_ray_history_views[0])];
    let god_ray_1_info = [post_image_info(color_sampler, god_ray_history_views[1])];
    // TAA is no longer part of the production AA path. Keep these bindings valid by pointing
    // them at the current MRTs; the shader only selects them when stable temporal metadata is
    // explicitly enabled by a legacy caller.
    let taa_depth_info = [post_image_info(data_sampler, scene_depth_view)];
    let taa_normal_info = [post_image_info(data_sampler, scene_normal_roughness_view)];
    let writes = [
        vk::WriteDescriptorSet::default()
            .dst_set(descriptor_set)
            .dst_binding(POST_SCENE_COLOR_BINDING)
            .descriptor_type(vk::DescriptorType::COMBINED_IMAGE_SAMPLER)
            .image_info(&color_info),
        vk::WriteDescriptorSet::default()
            .dst_set(descriptor_set)
            .dst_binding(POST_SCENE_DEPTH_BINDING)
            .descriptor_type(vk::DescriptorType::COMBINED_IMAGE_SAMPLER)
            .image_info(&depth_info),
        vk::WriteDescriptorSet::default()
            .dst_set(descriptor_set)
            .dst_binding(POST_SCENE_NORMAL_ROUGHNESS_BINDING)
            .descriptor_type(vk::DescriptorType::COMBINED_IMAGE_SAMPLER)
            .image_info(&normal_roughness_info),
        vk::WriteDescriptorSet::default()
            .dst_set(descriptor_set)
            .dst_binding(POST_SCENE_TRANSPARENT_NORMAL_ROUGHNESS_BINDING)
            .descriptor_type(vk::DescriptorType::COMBINED_IMAGE_SAMPLER)
            .image_info(&transparent_normal_roughness_info),
        vk::WriteDescriptorSet::default()
            .dst_set(descriptor_set)
            .dst_binding(POST_BLOOM_BINDING)
            .descriptor_type(vk::DescriptorType::COMBINED_IMAGE_SAMPLER)
            .image_info(&bloom_info),
        vk::WriteDescriptorSet::default()
            .dst_set(descriptor_set)
            .dst_binding(POST_GOD_RAY_0_BINDING)
            .descriptor_type(vk::DescriptorType::COMBINED_IMAGE_SAMPLER)
            .image_info(&god_ray_0_info),
        vk::WriteDescriptorSet::default()
            .dst_set(descriptor_set)
            .dst_binding(POST_GOD_RAY_1_BINDING)
            .descriptor_type(vk::DescriptorType::COMBINED_IMAGE_SAMPLER)
            .image_info(&god_ray_1_info),
        vk::WriteDescriptorSet::default()
            .dst_set(descriptor_set)
            .dst_binding(POST_TAA_LINEAR_DEPTH_BINDING)
            .descriptor_type(vk::DescriptorType::COMBINED_IMAGE_SAMPLER)
            .image_info(&taa_depth_info),
        vk::WriteDescriptorSet::default()
            .dst_set(descriptor_set)
            .dst_binding(POST_TAA_NORMAL_BINDING)
            .descriptor_type(vk::DescriptorType::COMBINED_IMAGE_SAMPLER)
            .image_info(&taa_normal_info),
    ];

    // Safety: descriptor set, sampler, and image view belong to this device and remain alive.
    unsafe {
        device.update_descriptor_sets(&writes, &[]);
    }
}

/// Builds one post-pass sampled-image descriptor with shader-read layout.
fn post_image_info(sampler: vk::Sampler, image_view: vk::ImageView) -> vk::DescriptorImageInfo {
    vk::DescriptorImageInfo::default()
        .sampler(sampler)
        .image_view(image_view)
        .image_layout(vk::ImageLayout::SHADER_READ_ONLY_OPTIMAL)
}

/// Returns a created handle from a build slot with a resource-specific panic message.
fn expect_created<T: Copy>(value: Option<T>, label: &'static str) -> T {
    value.unwrap_or_else(|| panic!("{label} was not created"))
}

/// Moves a created handle out of a build slot with a resource-specific panic message.
fn take_created<T>(value: &mut Option<T>, label: &'static str) -> T {
    value
        .take()
        .unwrap_or_else(|| panic!("{label} was not created"))
}

/// Creates the full-screen post graphics pipeline.
fn create_post_pipeline(
    device: &Device,
    pipeline_layout: vk::PipelineLayout,
    render_pass: vk::RenderPass,
    fragment_shader_code: &[u8],
) -> Result<vk::Pipeline, VulkanError> {
    let vertex_shader = shader::create_shader_module(device, VERTEX_SHADER)?;
    let fragment_shader = match shader::create_shader_module(device, fragment_shader_code) {
        Ok(shader) => shader,
        Err(error) => {
            shader::destroy_shader_module(device, vertex_shader);
            return Err(error);
        }
    };
    let pipeline = create_graphics_pipeline(
        device,
        pipeline_layout,
        render_pass,
        vertex_shader,
        fragment_shader,
    );

    shader::destroy_shader_module(device, fragment_shader);
    shader::destroy_shader_module(device, vertex_shader);
    pipeline
}

/// Creates fixed-function state for a full-screen triangle post pass.
fn create_graphics_pipeline(
    device: &Device,
    pipeline_layout: vk::PipelineLayout,
    render_pass: vk::RenderPass,
    vertex_shader: vk::ShaderModule,
    fragment_shader: vk::ShaderModule,
) -> Result<vk::Pipeline, VulkanError> {
    let shader_stages = [
        vk::PipelineShaderStageCreateInfo::default()
            .stage(vk::ShaderStageFlags::VERTEX)
            .module(vertex_shader)
            .name(SHADER_ENTRY),
        vk::PipelineShaderStageCreateInfo::default()
            .stage(vk::ShaderStageFlags::FRAGMENT)
            .module(fragment_shader)
            .name(SHADER_ENTRY),
    ];
    let vertex_input = vk::PipelineVertexInputStateCreateInfo::default();
    let input_assembly = vk::PipelineInputAssemblyStateCreateInfo::default()
        .topology(vk::PrimitiveTopology::TRIANGLE_LIST);
    let viewport_state = vk::PipelineViewportStateCreateInfo::default()
        .viewport_count(1)
        .scissor_count(1);
    let rasterization = vk::PipelineRasterizationStateCreateInfo::default()
        .polygon_mode(vk::PolygonMode::FILL)
        .cull_mode(vk::CullModeFlags::NONE)
        .front_face(vk::FrontFace::CLOCKWISE)
        .line_width(1.0);
    let multisample = vk::PipelineMultisampleStateCreateInfo::default()
        .rasterization_samples(vk::SampleCountFlags::TYPE_1);
    let color_blend_attachment = vk::PipelineColorBlendAttachmentState::default().color_write_mask(
        vk::ColorComponentFlags::R
            | vk::ColorComponentFlags::G
            | vk::ColorComponentFlags::B
            | vk::ColorComponentFlags::A,
    );
    let color_blend_attachments = [color_blend_attachment];
    let color_blend =
        vk::PipelineColorBlendStateCreateInfo::default().attachments(&color_blend_attachments);
    let dynamic_states = [vk::DynamicState::VIEWPORT, vk::DynamicState::SCISSOR];
    let dynamic_state =
        vk::PipelineDynamicStateCreateInfo::default().dynamic_states(&dynamic_states);
    let pipeline_info = vk::GraphicsPipelineCreateInfo::default()
        .stages(&shader_stages)
        .vertex_input_state(&vertex_input)
        .input_assembly_state(&input_assembly)
        .viewport_state(&viewport_state)
        .rasterization_state(&rasterization)
        .multisample_state(&multisample)
        .color_blend_state(&color_blend)
        .dynamic_state(&dynamic_state)
        .layout(pipeline_layout)
        .render_pass(render_pass)
        .subpass(0);
    let pipeline_infos = [pipeline_info];

    // Safety: pipeline state references are local and render pass compatibility is fixed.
    match unsafe {
        device.create_graphics_pipelines(vk::PipelineCache::null(), &pipeline_infos, None)
    } {
        Ok(mut pipelines) => Ok(pipelines.remove(0)),
        Err((pipelines, error)) => {
            for pipeline in pipelines {
                destroy_pipeline(device, pipeline);
            }
            Err(VulkanError::Vk(error))
        }
    }
}

/// Views a push-constant struct as bytes for Vulkan command recording.
fn push_constant_bytes<T>(value: &T) -> &[u8] {
    // Safety: push constants are plain repr(C) data and are copied during command recording.
    unsafe { std::slice::from_raw_parts((value as *const T).cast::<u8>(), size_of::<T>()) }
}

/// Destroys one descriptor set layout.
fn destroy_descriptor_set_layout(device: &Device, layout: vk::DescriptorSetLayout) {
    if layout != vk::DescriptorSetLayout::null() {
        // Safety: descriptor set layouts are destroyed after dependent objects.
        unsafe { device.destroy_descriptor_set_layout(layout, None) };
    }
}

/// Destroys one pipeline layout.
fn destroy_pipeline_layout(device: &Device, layout: vk::PipelineLayout) {
    if layout != vk::PipelineLayout::null() {
        // Safety: all pipelines using this layout are destroyed first.
        unsafe { device.destroy_pipeline_layout(layout, None) };
    }
}

/// Destroys one descriptor pool and descriptor sets allocated from it.
fn destroy_descriptor_pool(device: &Device, pool: vk::DescriptorPool) {
    if pool != vk::DescriptorPool::null() {
        // Safety: descriptor sets from this pool are no longer in use.
        unsafe { device.destroy_descriptor_pool(pool, None) };
    }
}

/// Destroys one sampler.
fn destroy_sampler(device: &Device, sampler: vk::Sampler) {
    if sampler != vk::Sampler::null() {
        // Safety: the sampler was created by this device and is no longer referenced.
        unsafe { device.destroy_sampler(sampler, None) };
    }
}

/// Destroys one graphics pipeline.
fn destroy_pipeline(device: &Device, pipeline: vk::Pipeline) {
    if pipeline != vk::Pipeline::null() {
        // Safety: the pipeline was created by this device and is no longer referenced.
        unsafe { device.destroy_pipeline(pipeline, None) };
    }
}

#[cfg(test)]
mod tests {
    use super::{
        PostPushConstants, SMAA_AREA_TEX, SMAA_AREA_TEX_HEIGHT, SMAA_AREA_TEX_WIDTH,
        SMAA_SEARCH_TEX, SMAA_SEARCH_TEX_HEIGHT, SMAA_SEARCH_TEX_WIDTH,
    };
    use crate::protocol::RenderFeatureToggles;

    #[test]
    fn smaa_lookup_payloads_match_reference_dimensions() {
        assert_eq!(
            SMAA_AREA_TEX.len(),
            (SMAA_AREA_TEX_WIDTH * SMAA_AREA_TEX_HEIGHT * 2) as usize
        );
        assert_eq!(
            SMAA_SEARCH_TEX.len(),
            (SMAA_SEARCH_TEX_WIDTH * SMAA_SEARCH_TEX_HEIGHT) as usize
        );
    }

    #[test]
    fn fast_post_requires_every_expensive_feature_to_be_disabled() {
        let disabled = PostPushConstants::default();
        assert!(disabled.uses_fast_pipeline());

        // SMAA is a separate three-pass chain, so enabling it does not force the composition
        // shader off its one-sample fast path.
        let mut aa = disabled;
        aa.aa[3] = 1.0;
        assert!(aa.uses_fast_pipeline());

        let mut ssao = disabled;
        ssao.temporal[1] = RenderFeatureToggles::disabled().with_ssao(true).bits() as f32;
        ssao.ssao[0] = 1.0;
        assert!(!ssao.uses_fast_pipeline());

        let mut ssr = disabled;
        ssr.temporal[1] = RenderFeatureToggles::disabled().with_ssr(true).bits() as f32;
        ssr.ssr[0] = 1.0;
        ssr.ssr[1] = 1.0;
        assert!(!ssr.uses_fast_pipeline());

        let mut bloom = disabled;
        bloom.temporal[1] = RenderFeatureToggles::disabled().with_bloom(true).bits() as f32;
        bloom.bloom[0] = 1.0;
        assert!(!bloom.uses_fast_pipeline());

        let mut god_rays = disabled;
        god_rays.temporal[1] = RenderFeatureToggles::disabled().with_god_rays(true).bits() as f32;
        god_rays.bloom[3] = 1.0;
        god_rays.god_ray_source1[3] = 1.0;
        assert!(!god_rays.uses_fast_pipeline());

        let mut debug_view = disabled;
        debug_view.features[2] = 1.0;
        assert!(!debug_view.uses_fast_pipeline());
    }

    #[test]
    fn fast_post_matches_compound_shader_enable_conditions() {
        let mut ssr_without_steps = PostPushConstants::default();
        ssr_without_steps.ssr[0] = 1.0;
        assert!(ssr_without_steps.uses_fast_pipeline());

        let mut god_rays_without_source = PostPushConstants::default();
        god_rays_without_source.bloom[3] = 1.0;
        assert!(god_rays_without_source.uses_fast_pipeline());
    }
}
